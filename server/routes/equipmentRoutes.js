const express = require('express')
const router = express.Router()
const { requireRole } = require('../middleware/roleAuth.js')
const { getEquipment, createEquipment, updateEquipment, deleteEquipment } = require('../controllers/equipmentController.js')
const { createExcelImportController } = require('../controllers/excelImportController.js')
const excelImport = createExcelImportController('equipment')
const exportExcel = require('../controllers/excelExportController.js').createExcelExportController('equipment')
const bulkActions = require('../controllers/bulkRecordController.js').createBulkRecordController('equipment')
router.get('/', requireRole('MIS','Inventory Staff','Teacher','Dean','Others'), getEquipment) // CP85: Report Issue needs the same asset list Teachers get
router.post('/export', requireRole('MIS','Inventory Staff','Teacher','Dean'), exportExcel)
router.post('/bulk-delete', requireRole('MIS','Inventory Staff'), bulkActions.bulkDelete)
router.post('/undo-bulk-delete/:undoId', requireRole('MIS','Inventory Staff'), bulkActions.undoDelete)
router.get('/import-template', requireRole('MIS','Inventory Staff'), require('../controllers/importTemplateController.js').createImportTemplateController('equipment'))
router.post('/import-preview', requireRole('MIS','Inventory Staff'), (req, res, next) => { if (!req.body?.fileBase64) return res.status(400).json({ message: 'Choose a valid .xlsx file (maximum 5 MB).' }); return excelImport.preview(req, res, next) })
router.post('/import', requireRole('MIS','Inventory Staff'), excelImport.commit)
router.post('/', requireRole('MIS','Inventory Staff'), createEquipment)
router.put('/:id', requireRole('MIS','Inventory Staff'), updateEquipment)
router.delete('/:id', requireRole('MIS','Inventory Staff'), deleteEquipment)
module.exports = router
