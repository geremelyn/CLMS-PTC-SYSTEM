// CP102: Audit Log "Print / Save PDF" uses the SAME shared PTC Letter template as the other module PDFs (incl. CP101).
// Pure builders (no DOM, no database, no HTTP). Page wiring is checked statically against AuditLog.jsx.
const test = require('node:test')
const assert = require('node:assert')
const fs = require('node:fs')
const path = require('node:path')
const { pathToFileURL } = require('node:url')
const U = f => import(pathToFileURL(path.join(__dirname, '../../client/src/utils', f)).href)
const printedBy = { surname: 'Dela Cruz', first_name: 'Juan', middle_initial: 'P' }
const roleLabel = l => (l.role === 'Teacher' && l.program ? `${l.program}-Teacher` : l.role === 'Inventory Staff' ? 'MIS Staff' : l.role || '—')
const LOGS = [
  { id: 1, action: 'LOGIN', description: 'User logged in.', created_at: '2026-10-01T08:00:00Z', full_name: 'Ana Reyes', username: '2024-0001', role: 'Teacher', program: 'BSIT' },
  { id: 2, action: 'DELETE <b>X</b>', description: 'Deleted "Lab & 1"', created_at: null, full_name: '', username: '', role: 'Inventory Staff' },
]
async function html(logs = LOGS, extra = {}) {
  global.localStorage = { getItem: () => JSON.stringify(printedBy) }
  const M = await U('auditLogPdf.js')
  return M.buildAuditLogPdfHtml(logs, { roleLabel, now: new Date('2026-11-10T04:00:00Z'), ...extra })
}
const common = h => ({
  header: (h.match(/<header class="clms-pdf-header">[\s\S]*?<\/header>/) || [''])[0],
  printed: (h.match(/<p class="clms-pdf-printed-by">[^<]*<\/p>/) || [''])[0].replace(/(Printed by|Generated By):/, 'LABEL:'), // CP142: Laboratories says Generated By; name part must match
  page: (h.match(/@page \{ size: 8\.5in 11in; margin: [^}]*\}/) || [''])[0],
  tableCss: (h.match(/\.pdf-title\{[\s\S]*?\.pdf-empty\{[^}]*\}/) || [''])[0],
  footer: (h.match(/@page\{@bottom-left[^\n]*\}\}/) || [''])[0].replace(/Generated [^"]*/, 'Generated X'),
})

test('identical header, Printed-by line, Letter page, table CSS and footer as Laboratories, Users and Maintenance History PDFs', async () => {
  global.localStorage = { getItem: () => JSON.stringify(printedBy) }
  const [L, Us, MH] = await Promise.all([U('laboratoriesPdf.js'), U('usersPdf.js'), U('maintenanceHistoryPdf.js')])
  const mine = common(await html())
  const refs = [common(L.buildLaboratoriesPdfHtml([])), common(Us.buildUsersPdfHtml([])), common(MH.buildMaintenanceHistoryPdfHtml([], { getAsset: () => ({}) }))]
  for (const ref of refs) for (const key of Object.keys(ref)) { assert.ok(mine[key], key); assert.equal(mine[key], ref[key], key) }
})
test('header has PTC + ICCT logos, school name, address and the Institute line', async () => {
  const { header } = common(await html())
  for (const t of ['clms-logo.png', 'icct-logo.png', 'PATEROS TECHNOLOGICAL COLLEGE', 'College St., Sto. Rosario Kanluran, Pateros, Metro Manila', 'Institute of Information and Computing Technology']) assert.ok(header.includes(t), t)
})
test('Generated By (CP143) uses the logged-in user; explicit user wins; none -> no line', async () => {
  assert.match(await html(), /Generated By: Dela Cruz, Juan, P\./)
  assert.match(await html(LOGS, { printedBy: { surname: 'Santos', first_name: 'Maria' } }), /Generated By: Santos, Maria</)
  global.localStorage = { getItem: () => null }
  const M = await U('auditLogPdf.js')
  assert.ok(!/clms-pdf-printed-by">/.test(M.buildAuditLogPdfHtml(LOGS, { roleLabel })))
})
test('same columns as the screen table; every row printed with the screen wording', async () => {
  const h = await html()
  for (const col of ['No.', 'Action', 'Description', 'Date &amp; Time', 'Recorded By', 'ID Number', 'Role']) assert.ok(h.includes(`>${col}</th>`), col)
  assert.match(h, /<h2 class="pdf-title">AUDIT LOG<\/h2>/); assert.match(h, /Total records: 2/)
  for (const t of ['LOGIN', 'User logged in.', 'Ana Reyes', '2024-0001', 'BSIT-Teacher', 'System', 'MIS Staff']) assert.ok(h.includes(t), t)
  assert.ok(!h.includes('Inventory Staff'))
  assert.equal((h.match(/<tr><td class="c-no">/g) || []).length, 2)
  assert.match(h, /<td class="c-date">—<\/td>/)
})
test('user text is HTML-escaped', async () => {
  const h = await html()
  assert.ok(!h.includes('<b>X</b>')); assert.ok(h.includes('DELETE &lt;b&gt;X&lt;/b&gt;')); assert.ok(h.includes('Deleted &quot;Lab &amp; 1&quot;'))
})
test('search filter shown; empty state; long lists are not truncated', async () => {
  assert.match(await html(LOGS, { search: 'login' }), /Search filter: “login”/)
  assert.match(await html([], { search: 'zzz' }), /No audit activities match your search\./)
  const many = Array.from({ length: 300 }, (_, i) => ({ ...LOGS[0], id: i }))
  assert.equal(((await html(many)).match(/<tr><td class="c-no">/g) || []).length, 300)
})
test('AuditLog.jsx wiring: shared builder on all filtered rows, no raw window.print, Super Admin-only gate unchanged', () => {
  const src = fs.readFileSync(path.join(__dirname, '../../client/src/pages/AuditLog.jsx'), 'utf8')
  assert.match(src, /onClick=\{handlePrintPdf\}>Save as PDF<\/button>/ /* CP186 rename */)
  assert.ok(!/window\.print\(\)/.test(src))
  assert.match(src, /printHtmlDocument\(buildAuditLogPdfHtml\(filteredLogs, \{ roleLabel, search: searchTerm\.trim\(\), eventType: activeEventType, logoBase: window\.location\.origin \}\)\)/)
  assert.match(src, /if \(user\?\.role !== 'MIS'\) return <div className="audit-denied">/)
  assert.match(src, /if \(user\?\.role === 'MIS'\) \{/)
})
test('Maintenance History PDF (CP101) is unchanged', () => {
  const src = fs.readFileSync(path.join(__dirname, '../../client/src/pages/Maintenance.jsx'), 'utf8')
  assert.match(src, /buildMaintenanceHistoryPdfHtml\(visibleMaintenanceHistory/)
})
