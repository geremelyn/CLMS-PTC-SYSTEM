const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = file => fs.readFileSync(path.resolve(__dirname, file), 'utf8')

test('CP164: equipment has a separate Status (equipment_state) saved on create and update; Condition stays in `status` and keeps driving Maintenance', () => {
  const controller = read('../controllers/equipmentController.js')
  assert.match(controller, /INSERT INTO equipment\([\s\S]*equipment_state,\s*status,/)
  assert.match(controller, /SET equipment_type = \?,[\s\S]*equipment_state = \?,\s*status = \?/)
  assert.match(controller, /syncEquipmentMaintenance|syncAndAudit/)
  const { needsMaintenance } = require('../utils/equipmentMaintenanceSync.js')
  assert.equal(needsMaintenance('NOT WORKING'), true)
  assert.equal(needsMaintenance('Working'), false)
  assert.equal(needsMaintenance('INACTIVE'), false)
})
test('CP164: schema adds equipment_state once and migrates legacy ACTIVE / INACTIVE condition values idempotently', () => {
  const schema = read('../database/ensureSchema.js')
  assert.match(schema, /addColumn\('equipment', 'equipment_state'/)
  assert.match(schema, /SET equipment_state = 'INACTIVE', status = 'WORKING' WHERE UPPER\(TRIM\(status\)\) = 'INACTIVE'/)
  assert.match(schema, /SET status = 'WORKING' WHERE UPPER\(TRIM\(status\)\) = 'ACTIVE'/)
})
test('CP164: equipment_state is an allowed custom-option category with ACTIVE / INACTIVE built in', () => {
  const lookup = require('../controllers/lookupOptionController.js')
  assert.ok(lookup.ALLOWED_CATEGORIES.has('equipment_state'))
  assert.deepEqual(lookup.BUILT_IN_OPTIONS.equipment_state, ['ACTIVE', 'INACTIVE'])
})
test('CP164: Equipment page - no "Search all equipment fields" text, 5 rows per page, typeable page number, no rows-per-page dropdown, Status + Condition dropdowns', () => {
  const page = read('../../client/src/pages/Equipment.jsx')
  assert.doesNotMatch(page, /Search all equipment fields/)
  assert.match(page, /const PAGE_SIZE = 5/)
  assert.doesNotMatch(page, /Rows per page/)
  assert.match(page, /aria-label="Page number"/)
  assert.match(page, /ariaLabel="Status"/); assert.match(page, /ariaLabel="Condition"/)
  assert.match(page, /'Clear Selection' : 'Select All'/)
})
test('CP164/CP188: Import popup fixed layout is opt-in (Equipment, Laboratories, Computers; not Users) and removes the X button', () => {
  const panel = read('../../client/src/components/ExcelImportPanel.jsx')
  assert.match(panel, /fixedLayout = false/); assert.match(panel, /!fixedLayout && <button type="button" className="excel-import-close"/)
  for (const page of ['Equipment', 'Computers', 'Laboratories']) assert.match(read(`../../client/src/pages/${page}.jsx`), /fixedLayout: true/)
  assert.doesNotMatch(read('../../client/src/pages/Users.jsx'), /fixedLayout/)
  assert.match(panel, /createPortal\(<div className="excel-import-backdrop"/) // CP188: popup is rendered at the page root (position:fixed was relative to a transformed/blurred ancestor)
})
