// CP98: the five module PDFs (Users, Computers, Laboratories, Equipment, My Reports) all use ONE template:
// same PTC header/logos/school/address/IICT line, Letter page, shared table CSS, footer and the CP97 "Printed by" line.
const test = require('node:test')
const assert = require('node:assert')
const path = require('node:path')
const { pathToFileURL } = require('node:url')
const U = f => import(pathToFileURL(path.join(__dirname, '../../client/src/utils', f)).href)
const printedBy = { surname: 'Dela Cruz', first_name: 'Juan', middle_initial: 'P' }

async function samples() {
  global.localStorage = { getItem: () => JSON.stringify(printedBy) }
  const [L, C, Us, E, M] = await Promise.all(['laboratoriesPdf.js', 'computersPdf.js', 'usersPdf.js', 'equipmentPdf.js', 'myReportsPdf.js'].map(U))
  return {
    Laboratories: L.buildLaboratoriesPdfHtml([{ laboratory_name: 'Lab 1', capacity: 30, status: 'AVAILABLE' }]),
    Computers: C.buildComputersPdfHtml([]),
    'User Accounts': Us.buildUsersPdfHtml([]),
    Equipment: E.buildEquipmentPdfHtml([]),
    'My Reports': M.buildMyReportsPdfHtml([]),
  }
}
// Everything that must be identical across the five documents (header block + shared CSS).
const common = html => ({
  header: (html.match(/<header class="clms-pdf-header">[\s\S]*?<\/header>/) || [''])[0],
  printed: (html.match(/<p class="clms-pdf-printed-by">[^<]*<\/p>/) || [''])[0].replace(/(Printed by|Generated By):/, 'LABEL:'), // CP142: label differs (Generated By on the four signed module PDFs); the name part must stay identical
  page: (html.match(/@page \{ size: 8\.5in 11in; margin: [^}]*\}/) || [''])[0],
  tableCss: (html.match(/\.pdf-title\{[\s\S]*?\.pdf-empty\{[^}]*\}/) || [''])[0],
  footer: (html.match(/@page\{@bottom-left[^\n]*\}\}/) || [''])[0].replace(/Generated [^"]*/, 'Generated X'),
})

test('all five PDFs share the identical header, Printed-by line, Letter page, table CSS and footer', async () => {
  const s = await samples()
  const ref = common(s.Laboratories)
  for (const [name, html] of Object.entries(s)) {
    const c = common(html)
    for (const key of Object.keys(ref)) { assert.ok(c[key], `${name}: ${key} present`); assert.equal(c[key], ref[key], `${name}: ${key} identical`) }
  }
})
test('header carries PTC + ICCT logos, school name, address and the IICT line', async () => {
  const { header } = common((await samples()).Equipment)
  for (const t of ['clms-logo.png', 'icct-logo.png', 'PATEROS TECHNOLOGICAL COLLEGE', 'College St., Sto. Rosario Kanluran, Pateros, Metro Manila', 'Institute of Information and Computing Technology'])
    assert.ok(header.includes(t), t)
})
test('CP97 name line is kept on every PDF (CP142/CP143: "Generated By" on all five)', async () => {
  for (const [name, html] of Object.entries(await samples())) assert.match(html, /Generated By: Dela Cruz, Juan, P\./, name)
})
test('every PDF has a title, the same meta line style, and a pdf-table', async () => {
  for (const [name, html] of Object.entries(await samples())) { assert.match(html, /<h2 class="pdf-title">/, name); assert.match(html, /<p class="pdf-meta">/, name); assert.match(html, /<table class="pdf-table">/, name) }
})
