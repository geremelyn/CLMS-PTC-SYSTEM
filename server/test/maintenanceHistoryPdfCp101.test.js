// CP101: Maintenance History "Print PDF" uses the SAME shared PTC Letter template as the other module PDFs.
// Pure builders (no DOM, no database, no HTTP). Page wiring is checked statically against Maintenance.jsx.
const test = require('node:test')
const assert = require('node:assert')
const fs = require('node:fs')
const path = require('node:path')
const { pathToFileURL } = require('node:url')
const U = f => import(pathToFileURL(path.join(__dirname, '../../client/src/utils', f)).href)
const printedBy = { surname: 'Dela Cruz', first_name: 'Juan', middle_initial: 'P' }
const getAsset = r => ({ tag: r.tag, type: r.type, name: r.name || '' })
const REC = [
  { id: 1, tag: 'PC-01', type: 'Computer', name: 'Lab1-PC1', reported_by_name: 'Ana Reyes', reported_by_username: '2024-0001', reported_by_program: 'BSIT', reported_by_role: 'Teacher', issue_description: 'Screen flickers', status: 'COMPLETED', maintenance_note: 'Cable replaced', date_reported: '2026-10-01T08:00:00Z', date_resolved: '2026-10-02T09:30:00Z' },
  { id: 2, tag: 'EQ-07', type: 'Mouse', reported_by_name: 'Staff <b>One</b>', reported_by_username: 'S-1', reported_by_program: '', reported_by_role: 'Inventory Staff', issue_description: '', status: 'CLOSED', status_other: 'Replaced & closed', date_reported: '2026-10-03T08:00:00Z', date_resolved: null },
]
async function html(records = REC, extra = {}) {
  global.localStorage = { getItem: () => JSON.stringify(printedBy) }
  const [M] = await Promise.all([U('maintenanceHistoryPdf.js')])
  return M.buildMaintenanceHistoryPdfHtml(records, { getAsset, now: new Date('2026-11-10T04:00:00Z'), ...extra })
}
const common = h => ({
  header: (h.match(/<header class="clms-pdf-header">[\s\S]*?<\/header>/) || [''])[0],
  printed: (h.match(/<p class="clms-pdf-printed-by">[^<]*<\/p>/) || [''])[0].replace(/(Printed by|Generated By):/, 'LABEL:'), // CP142: Laboratories says Generated By; name part must match
  page: (h.match(/@page \{ size: 8\.5in 11in; margin: [^}]*\}/) || [''])[0],
  tableCss: (h.match(/\.pdf-title\{[\s\S]*?\.pdf-empty\{[^}]*\}/) || [''])[0],
  footer: (h.match(/@page\{@bottom-left[^\n]*\}\}/) || [''])[0].replace(/Generated [^"]*/, 'Generated X'),
})

test('identical header, Printed-by line, Letter page, table CSS and footer as the Laboratories/Users PDFs', async () => {
  global.localStorage = { getItem: () => JSON.stringify(printedBy) }
  const [L, Us] = await Promise.all([U('laboratoriesPdf.js'), U('usersPdf.js')])
  const mine = common(await html())
  for (const ref of [common(L.buildLaboratoriesPdfHtml([])), common(Us.buildUsersPdfHtml([]))])
    for (const key of Object.keys(ref)) { assert.ok(mine[key], key); assert.equal(mine[key], ref[key], key) }
})
test('header has PTC + ICCT logos, school name, address and the Institute line', async () => {
  const { header } = common(await html())
  for (const t of ['clms-logo.png', 'icct-logo.png', 'PATEROS TECHNOLOGICAL COLLEGE', 'College St., Sto. Rosario Kanluran, Pateros, Metro Manila', 'Institute of Information and Computing Technology']) assert.ok(header.includes(t), t)
})
test('Generated By (CP143) uses the actual logged-in user (explicit user wins; none -> no line)', async () => {
  assert.match(await html(), /Generated By: Dela Cruz, Juan, P\./)
  assert.match(await html(REC, { printedBy: { surname: 'Santos', first_name: 'Maria', middle_initial: '' } }), /Generated By: Santos, Maria</)
  global.localStorage = { getItem: () => null }
  const M = await U('maintenanceHistoryPdf.js')
  assert.ok(!/clms-pdf-printed-by">/.test(M.buildMaintenanceHistoryPdfHtml(REC, { getAsset })))
})
test('same columns as the on-screen history table, and every record is printed with the on-screen wording', async () => {
  const h = await html()
  for (const col of ['No.', 'Asset', 'Reported By (ID Number, Name, Program, Role)', 'Issue', 'Status', 'Reported / Resolved Date &amp; Time']) assert.ok(h.includes(`>${col}</th>`), col)
  assert.match(h, /<h2 class="pdf-title">MAINTENANCE HISTORY<\/h2>/)
  assert.match(h, /Total records: 2/)
  for (const t of ['PC-01', 'Computer - Lab1-PC1', 'Ana Reyes', 'ID Number: 2024-0001', 'BSIT · Teacher', 'Screen flickers', 'Completed', 'Cable replaced', 'EQ-07', 'MIS Staff', 'No issue description', 'Replaced &amp; closed', 'Resolved']) assert.ok(h.includes(t), t)
  assert.ok(!h.includes('Inventory Staff'), 'role is shown as MIS Staff')
  assert.equal((h.match(/<tr><td class="c-no">/g) || []).length, 2)
})
test('missing resolved date shows "-" like the screen; user text is HTML-escaped', async () => {
  const h = await html()
  assert.match(h, /<strong>Resolved<\/strong><small>-<\/small>/)
  assert.ok(!h.includes('<b>One</b>')); assert.ok(h.includes('Staff &lt;b&gt;One&lt;/b&gt;'))
})
test('search filter is stated in the meta line; empty result prints a clear empty row', async () => {
  assert.match(await html(REC, { search: 'flicker' }), /Search filter: “flicker”/)
  const empty = await html([], { search: 'zzz' })
  assert.match(empty, /Total records: 0/); assert.match(empty, /No maintenance history records match your search\./)
})
test('large lists are not truncated (all pages, not just the visible 10)', async () => {
  const many = Array.from({ length: 137 }, (_, i) => ({ ...REC[0], id: i + 1, tag: `PC-${i}` }))
  assert.equal(((await html(many)).match(/<tr><td class="c-no">/g) || []).length, 137)
})
test('Maintenance.jsx wiring: Save as PDF button (CP169: beside Delete All) uses the shared builder, no raw window.print, access gating unchanged', async () => {
  const src = fs.readFileSync(path.join(__dirname, '../../client/src/pages/Maintenance.jsx'), 'utf8')
  assert.match(src, /onClick=\{handlePrintHistoryPdf\}>Save as PDF<\/button>/)
  assert.ok(!/window\.print\(\)/.test(src), 'no raw window.print left')
  assert.match(src, /printHtmlDocument\(buildMaintenanceHistoryPdfHtml\(visibleMaintenanceHistory, \{ getAsset: getAssetDetails, search: searchTerm\.trim\(\), logoBase: window\.location\.origin \}\)\)/)
  assert.match(src, /\{historyOnly && <section className="maintenance-panel" id="maintenance-history-section">/)
  assert.match(src, /const canUpdateMaintenance = \['MIS', 'Inventory Staff'\]\.includes\(user\?\.role\)/)
})
test('Audit Log page is separate from this checkpoint (CP101 left it alone; CP102 moved it to the shared template)', async () => {
  const src = fs.readFileSync(path.join(__dirname, '../../client/src/pages/AuditLog.jsx'), 'utf8')
  assert.ok(!/maintenanceHistoryPdf/.test(src))
})

// CP169: Save as PDF sits in the History toolbar bar directly before (left of) Delete All; the old panel-heading button is gone.
test('CP169: History bar order is ... Save as PDF, Delete All; no "Print PDF" label remains; active Maintenance page gets no PDF button', () => {
  const src = fs.readFileSync(path.join(__dirname, '../../client/src/pages/Maintenance.jsx'), 'utf8')
  assert.ok(!/Print PDF/.test(src.replace(/\/\/[^\n]*/g, '')), 'no Print PDF label in code')
  const bar = src.slice(src.indexOf('function renderBulkControls'), src.indexOf('function renderMaintenanceTable'))
  assert.ok(bar.indexOf('>Save as PDF</button>') > -1 && bar.indexOf('>Save as PDF</button>') < bar.indexOf('>Delete All</button>'))
  assert.match(src, /renderBulkControls\(historyOnly \? visibleMaintenanceHistory : visibleActiveMaintenance, historyOnly\)/)
  assert.ok(!/maintenance-panel-heading-actions"><button/.test(src))
})
