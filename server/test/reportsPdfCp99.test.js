// CP99: Reports "Print PDF" uses the shared PTC Letter template (same as the other five PDFs) with the CP97 Printed-by line.
const test = require('node:test')
const assert = require('node:assert')
const fs = require('node:fs')
const path = require('node:path')
const { pathToFileURL } = require('node:url')
const U = f => import(pathToFileURL(path.join(__dirname, '../../client/src/utils', f)).href)
const user = { surname: 'Dela Cruz', first_name: 'Juan', middle_initial: 'P' }

test('Reports PDF has the shared header, logos, address, IICT line, Letter page and Generated By (CP143)', async () => {
  global.localStorage = { getItem: () => JSON.stringify(user) }
  const { buildReportsPdfHtml } = await U('reportsPdf.js')
  const html = buildReportsPdfHtml('Reservation Reports', ['reserved_by', 'status'], [{ reserved_by: 'Ana <b>', status: 'APPROVED' }], { search: 'ana' })
  for (const t of ['clms-logo.png', 'icct-logo.png', 'PATEROS TECHNOLOGICAL COLLEGE', 'College St., Sto. Rosario Kanluran, Pateros, Metro Manila', 'Institute of Information and Computing Technology', 'Generated By: Dela Cruz, Juan, P.', '@page { size: 8.5in 11in', 'RESERVATION REPORTS', 'Total records: 1', 'Search filter: “ana”', 'Ana &lt;b&gt;'])
    assert.ok(html.includes(t), t)
  assert.doesNotMatch(html, /A4|landscape/)
  delete global.localStorage
})
test('same header / Printed-by / page / table CSS / footer blocks as the Laboratories PDF (one template)', async () => {
  global.localStorage = { getItem: () => JSON.stringify(user) }
  const { buildReportsPdfHtml } = await U('reportsPdf.js'), { buildLaboratoriesPdfHtml } = await U('laboratoriesPdf.js')
  const blocks = h => [/<header class="clms-pdf-header">[\s\S]*?<\/header>/, /<p class="clms-pdf-printed-by">[^<]*<\/p>/, /@page \{ size: 8\.5in 11in; margin: [^}]*\}/, /\.pdf-title\{[\s\S]*?\.pdf-empty\{[^}]*\}/].map(r => (h.match(r) || [''])[0].replace(/(Printed by|Generated By):/, 'LABEL:')) // CP142: label differs on the signed module PDFs
  const a = blocks(buildReportsPdfHtml('X', ['a'], [{ a: 1 }])), b = blocks(buildLaboratoriesPdfHtml([]))
  a.forEach((blk, i) => { assert.ok(blk); assert.equal(blk, b[i]) })
  delete global.localStorage
})
test('columns, cell wording and ALL filtered rows are kept; empty state works; wide reports shrink text', async () => {
  const { buildReportsPdfHtml } = await U('reportsPdf.js'), { displayReportColumn, formatReportValue } = await U('reportFormatting.mjs')
  const cols = ['reserved_by', 'status'], rows = Array.from({ length: 60 }, (_, i) => ({ reserved_by: 'U' + i, status: 'PENDING' }))
  const html = buildReportsPdfHtml('R', cols, rows)
  assert.equal((html.match(/<tr><td>/g) || []).length, 60)
  for (const c of cols) assert.ok(html.includes(`<th>${displayReportColumn(c)}</th>`))
  assert.ok(html.includes(`<td>${formatReportValue('PENDING')}</td>`))
  assert.match(buildReportsPdfHtml('R', cols, []), /No records match your search/)
  assert.doesNotMatch(html, /font-size:6\.5pt/)
  assert.match(buildReportsPdfHtml('R', Array.from({ length: 9 }, (_, i) => 'c' + i), []), /font-size:6\.5pt/)
})
test('Reports page prints through the shared template; the old window.print() path and other PDFs are untouched', () => {
  const rp = fs.readFileSync(path.join(__dirname, '../../client/src/pages/Reports.jsx'), 'utf8')
  assert.match(rp, /buildReportsPdfHtml\(title, columns, selectedCount \? selectedVisible\.map\(e => e\.row\) : filteredData/)
  assert.doesNotMatch(rp, /window\.print\(\)/)
  assert.match(rp, /isCustomRole \? <button type="button" onClick=\{saveMyReportsPdf\}/)
})
